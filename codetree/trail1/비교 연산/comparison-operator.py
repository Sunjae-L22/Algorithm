A, B = map(int, input().split())
if A >= B:
    print(1)
else:
    print(0)

if A > B:
    print(1)
else:
    print(0)

if B >= A:
    print(1)
else:
    print(0)

if B > A:
    print(1)
else:
    print(0)

if A == B:
    print(1)
    print(0)
else:
    print(0)
